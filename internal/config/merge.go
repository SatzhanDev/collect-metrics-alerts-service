package config

import "os"

// MergeField — обобщённая (generic) функция, реализующая единое правило
// приоритета для одной опции конфигурации: значение из файла (filePtr)
// подставляется через apply только если ни соответствующая переменная
// окружения envVar, ни флаг flagName не были заданы явно — флаги и
// переменные окружения имеют более высокий приоритет, чем файл конфигурации.
//
// T — тип конкретного поля (string, bool, int и т.д.). Одна и та же проверка
// приоритета работает для всех типов одинаково, поэтому логика вынесена сюда
// один раз, вместо того чтобы дублироваться отдельно для каждого поля
// и каждой конфигурации (сервера и агента).
func MergeField[T any](explicitFlags map[string]bool, envVar, flagName string, filePtr *T, apply func(T)) {
	if filePtr == nil {
		// В файле конфигурации это поле вообще не было указано.
		return
	}
	if os.Getenv(envVar) != "" {
		// Переменная окружения задана — она главнее файла, не трогаем.
		return
	}
	if explicitFlags[flagName] {
		// Флаг был передан явно в командной строке — он тоже главнее файла.
		return
	}

	apply(*filePtr)
}
